/// The generic matrix for models outside the table: the element-wise mean
/// of the table, rounded to 3 decimals.
#[rustfmt::skip]
pub(super) const GENERIC: [f64; 9] = [
    2.039, -1.142, 0.104,
    -0.220, 1.618, -0.397,
    0.042, -0.632, 1.589,
];

/// The generic white balance scales R and B (means of the table).
pub(super) const GENERIC_WB: (f64, f64) = (2.073, 1.672);

/// R-CR2-30: the table row whose CanonModelID equals MakerNote tag 0x0010.
fn row(model_id: Option<u32>) -> Option<&'static Row> {
    let id = model_id?;
    TABLE.iter().find(|r| r.0 == id)
}

/// The camera-to-sRGB matrix with every row divided by its sum, and
/// whether it came from the table. R-CR2-30: the row of the CanonModelID,
/// else the generic matrix. R-CR2-31: each row is divided by its sum.
pub(super) fn matrix(model_id: Option<u32>) -> ([[f64; 3]; 3], bool) {
    let (m, from_table) = match row(model_id) {
        Some(r) => (r.3, true),
        None => (GENERIC, false),
    };
    let mut out = [[0.0; 3]; 3];
    for (r, o) in out.iter_mut().enumerate() {
        let src = &m[3 * r..3 * r + 3];
        let sum: f64 = src.iter().sum();
        // R-CR2-51: a divisor must be greater than 0. Every row of the
        // table sums to about 1, so the guard only protects against a
        // broken table.
        let sum = if sum > 0.0 { sum } else { 1.0 };
        for (c, v) in o.iter_mut().enumerate() {
            *v = src[c] / sum;
        }
    }
    (out, from_table)
}

/// R-CR2-27: the index of R, G1, G2, B of the as-shot white balance in
/// ColorData, by the first matching row of the table of the
/// specification. `None` for ColorData2 and unknown layouts.
pub(super) fn wb_index(color_data: &[i32]) -> Option<usize> {
    let n = color_data.len();
    let version = color_data.first().copied();
    if n == 582 {
        // ColorData1: WB_RGGBLevelsAsShot at 25.
        Some(25)
    } else if n >= 67 && version.is_some_and(|v| (1..=15).contains(&v)) {
        // ColorData3, 4, 6, 7, 8: at 63.
        Some(63)
    } else if n >= 75 && matches!(version, Some(-3 | -4)) {
        // ColorData5: at 71.
        Some(71)
    } else {
        None
    }
}

/// R-CR2-28: the multipliers mR, mG, mB from the first available source:
/// ColorData (R-CR2-27) with four positive values, the D50 scales of the
/// CanonModelID row, the generic scales.
pub(super) fn white_balance(
    color_data: Option<&[i32]>,
    model_id: Option<u32>,
) -> ([f64; 3], WbSource) {
    if let Some(cd) = color_data {
        if let Some(q) = wb_index(cd).and_then(|i| cd.get(i..i + 4)) {
            if q.iter().all(|&v| v > 0) {
                // Source 1: G = (G1 + G2) / 2 > 0 (R-CR2-51).
                let g = f64::from(q[1] + q[2]) / 2.0;
                return (
                    [f64::from(q[0]) / g, 1.0, f64::from(q[3]) / g],
                    WbSource::AsShot,
                );
            }
        }
    }
    match row(model_id) {
        // Source 2.
        Some(r) => ([r.1, 1.0, r.2], WbSource::Table),
        // Source 3.
        None => ([GENERIC_WB.0, 1.0, GENERIC_WB.1], WbSource::Generic),
    }
}
